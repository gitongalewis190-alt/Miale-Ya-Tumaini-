#!/usr/bin/env python3
"""Build helper for the Miale ya Tumaini site. Run from the site root.

Creates:
  icons/icon-192.png and icons/icon-512.png  (pure Python, no dependencies)
  tokens.md                                  (token record with computed WCAG contrast)
  preview/miale-preview.html                 (single self-contained file for previewing)
"""
import os
import re
import struct
import zlib

SITE = os.getcwd()

# Tokens mirrored from styles.css. Keep in sync when styles.css changes.
LIGHT = {
    "--c-bg": "#F5F6F4", "--c-surface": "#FFFFFF", "--c-ink": "#14201F", "--c-muted": "#4F5E5C",
    "--c-line": "#D8DEDB", "--c-teal": "#0F3B38", "--c-red": "#B72A24", "--c-gold": "#F0B43C",
    "--c-on-teal": "#FFFFFF", "--c-on-red": "#FFFFFF", "--c-on-gold": "#14201F", "--c-focus": "#0F3B38",
    "--c-badge-sourced-bg": "#0F3B38", "--c-badge-sourced-ink": "#FFFFFF",
    "--c-badge-pending-bg": "#F0B43C", "--c-badge-pending-ink": "#14201F",
    "--c-badge-consent-bg": "#B72A24", "--c-badge-consent-ink": "#FFFFFF",
    "--c-badge-missing-bg": "#D8DEDB", "--c-badge-missing-ink": "#14201F",
    "--c-badge-draft-bg": "#FFFFFF", "--c-badge-draft-ink": "#14201F",
}
DARK = {
    "--c-bg": "#0D1918", "--c-surface": "#142423", "--c-ink": "#EAF1EF", "--c-muted": "#B4C6C2",
    "--c-line": "#2A3D3B", "--c-teal": "#7FD1C4", "--c-red": "#B72A24", "--c-gold": "#F0B43C",
    "--c-on-teal": "#0D1918", "--c-on-red": "#FFFFFF", "--c-on-gold": "#0D1918", "--c-focus": "#F0B43C",
    "--c-badge-sourced-bg": "#7FD1C4", "--c-badge-sourced-ink": "#0D1918",
    "--c-badge-pending-bg": "#F0B43C", "--c-badge-pending-ink": "#0D1918",
    "--c-badge-consent-bg": "#F2B8B4", "--c-badge-consent-ink": "#0D1918",
    "--c-badge-missing-bg": "#2A3D3B", "--c-badge-missing-ink": "#EAF1EF",
    "--c-badge-draft-bg": "#142423", "--c-badge-draft-ink": "#EAF1EF",
}

# (label, foreground token, background token, required ratio)
PAIRS = [
    ("Body text on page", "--c-ink", "--c-bg", 4.5),
    ("Body text on card", "--c-ink", "--c-surface", 4.5),
    ("Muted text on page", "--c-muted", "--c-bg", 4.5),
    ("Muted text on card", "--c-muted", "--c-surface", 4.5),
    ("Teal link text on card", "--c-teal", "--c-surface", 4.5),
    ("Primary button label", "--c-on-red", "--c-red", 4.5),
    ("Teal button label", "--c-on-teal", "--c-teal", 4.5),
    ("Focus ring on page", "--c-focus", "--c-bg", 3.0),
    ("Focus ring on card", "--c-focus", "--c-surface", 3.0),
    ("Badge: Sourced", "--c-badge-sourced-ink", "--c-badge-sourced-bg", 4.5),
    ("Badge: Pending verification", "--c-badge-pending-ink", "--c-badge-pending-bg", 4.5),
    ("Badge: Consent required", "--c-badge-consent-ink", "--c-badge-consent-bg", 4.5),
    ("Badge: Missing", "--c-badge-missing-ink", "--c-badge-missing-bg", 4.5),
    ("Badge: Draft", "--c-badge-draft-ink", "--c-badge-draft-bg", 4.5),
]


def luminance(hex_colour):
    channels = [int(hex_colour[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    linear = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
    return 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2]


def contrast(fg, bg):
    hi, lo = sorted([luminance(fg), luminance(bg)], reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def write_png(path, size, draw):
    rows = []
    for y in range(size):
        row = bytearray([0])
        for x in range(size):
            row.extend(draw(x, y, size))
        rows.append(bytes(row))
    raw = b"".join(rows)

    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    png = b"\x89PNG\r\n\x1a\n"
    png += chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 2, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(raw, 9))
    png += chunk(b"IEND", b"")
    with open(path, "wb") as fh:
        fh.write(png)


def hex_rgb(h):
    return [int(h[i:i + 2], 16) for i in (1, 3, 5)]


def icon_pixel(x, y, size):
    teal, gold, red = hex_rgb("#0F3B38"), hex_rgb("#F0B43C"), hex_rgb("#B72A24")
    cx = cy = size / 2
    d = ((x - cx) ** 2 + (y - cy) ** 2) ** 0.5
    if d < size * 0.28:
        return gold
    if size * 0.36 < d < size * 0.44 and (y > cy):
        return red
    return teal


def build_icons():
    os.makedirs(os.path.join(SITE, "icons"), exist_ok=True)
    write_png(os.path.join(SITE, "icons", "icon-192.png"), 192, icon_pixel)
    write_png(os.path.join(SITE, "icons", "icon-512.png"), 512, icon_pixel)


def build_tokens_md():
    lines = [
        "# Token record · Miale ya Tumaini",
        "",
        "Generated by `tools/build.py` from the token values in `styles.css`. Each text pair is measured against WCAG 2.2 AA thresholds (4.5:1 body text, 3:1 focus rings and large UI).",
        "",
        "Status is never conveyed by colour alone: every badge carries a text label.",
        "",
    ]
    for theme_name, tokens in (("Light", LIGHT), ("Dark", DARK)):
        lines += [f"## {theme_name} theme", "", "| Token | Value |", "|---|---|"]
        for name, value in tokens.items():
            lines.append(f"| `{name}` | `{value}` |")
        lines += ["", f"### {theme_name} contrast", "", "| Pair | Ratio | Required | Result |", "|---|---|---|---|"]
        for label, fg, bg, need in PAIRS:
            ratio = contrast(tokens[fg], tokens[bg])
            result = "Pass" if ratio >= need else "FAIL"
            lines.append(f"| {label} | {ratio:.2f}:1 | {need}:1 | {result} |")
        lines.append("")
    with open(os.path.join(SITE, "tokens.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    failures = [
        (theme, label)
        for theme, tokens in (("light", LIGHT), ("dark", DARK))
        for label, fg, bg, need in PAIRS
        if contrast(tokens[fg], tokens[bg]) < need
    ]
    return failures


def build_preview():
    with open(os.path.join(SITE, "index.html"), encoding="utf-8") as fh:
        html = fh.read()
    with open(os.path.join(SITE, "styles.css"), encoding="utf-8") as fh:
        css = fh.read()
    with open(os.path.join(SITE, "app.js"), encoding="utf-8") as fh:
        js = fh.read()
    html = html.replace('<link rel="stylesheet" href="styles.css">', "<style>\n" + css + "\n</style>")
    html = html.replace('<script src="app.js" defer></script>', "<script>\n" + js + "\n</script>")
    html = re.sub(r'<link rel="manifest"[^>]*>\n?', "", html)
    os.makedirs(os.path.join(SITE, "preview"), exist_ok=True)
    out = os.path.join(SITE, "preview", "miale-preview.html")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(html)
    return out


if __name__ == "__main__":
    build_icons()
    failures = build_tokens_md()
    preview = build_preview()
    print("icons: ok")
    print("tokens.md: written")
    print("contrast failures:", failures if failures else "none")
    print("preview:", preview, os.path.getsize(preview), "bytes")
